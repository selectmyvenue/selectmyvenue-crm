create or replace function public.smv_partner_analytics()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $function$
  with partner_venues as (
    select distinct p.venue_id
    from public.venue_partner_profiles p
    where p.user_id = (select auth.uid())
      and p.is_active = true
  ),
  metrics as (
    select
      count(*)::integer as total,
      count(*) filter (
        where a.assignment_status in ('assigned', 'viewed')
      )::integer as new_leads,
      count(*) filter (
        where a.first_contacted_at is not null
           or a.assignment_status in (
             'contacted', 'detailed_shared', 'follow_up',
             'site_visit', 'negotiation', 'booked', 'converted'
           )
      )::integer as responded,
      count(*) filter (
        where a.assignment_status = 'follow_up'
      )::integer as follow_ups,
      count(*) filter (
        where a.assignment_status = 'site_visit'
      )::integer as site_visits,
      count(*) filter (
        where a.assignment_status = 'negotiation'
      )::integer as negotiations,
      count(*) filter (
        where a.assignment_status in ('booked', 'converted')
      )::integer as bookings,
      count(*) filter (
        where a.assignment_status in ('lost', 'cancelled')
      )::integer as lost,
      round(
        (
          avg(
            extract(epoch from (a.first_contacted_at - a.assigned_at)) / 60.0
          ) filter (
            where a.first_contacted_at is not null
              and a.first_contacted_at >= a.assigned_at
          )
        )::numeric,
        1
      ) as avg_response_minutes
    from public.venue_enquiry_assignments a
    where a.venue_id in (select venue_id from partner_venues)
  )
  select jsonb_build_object(
    'total', m.total,
    'new_leads', m.new_leads,
    'responded', m.responded,
    'follow_ups', m.follow_ups,
    'site_visits', m.site_visits,
    'negotiations', m.negotiations,
    'bookings', m.bookings,
    'lost', m.lost,
    'response_rate', case
      when m.total = 0 then 0
      else round((m.responded::numeric / m.total::numeric) * 100, 1)
    end,
    'conversion_rate', case
      when m.total = 0 then 0
      else round((m.bookings::numeric / m.total::numeric) * 100, 1)
    end,
    'avg_response_minutes', coalesce(m.avg_response_minutes, 0)
  )
  from metrics m;
$function$;

create or replace function public.smv_admin_analytics()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $function$
declare
  result jsonb;
begin
  if not coalesce(public.smv_is_active_staff(), false) then
    raise exception 'Staff access required';
  end if;

  with assignment_metrics as (
    select
      count(*)::integer as total_assignments,
      count(*) filter (
        where first_contacted_at is not null
           or assignment_status in (
             'contacted', 'detailed_shared', 'follow_up',
             'site_visit', 'negotiation', 'booked', 'converted'
           )
      )::integer as responded,
      count(*) filter (
        where assignment_status in ('booked', 'converted')
      )::integer as bookings,
      count(*) filter (
        where assignment_status not in ('booked', 'converted', 'lost', 'cancelled')
          and first_contacted_at is null
          and assigned_at < now() - interval '24 hours'
      )::integer as unresponded_24h,
      round(
        (
          avg(
            extract(epoch from (first_contacted_at - assigned_at)) / 60.0
          ) filter (
            where first_contacted_at is not null
              and first_contacted_at >= assigned_at
          )
        )::numeric,
        1
      ) as avg_response_minutes
    from public.venue_enquiry_assignments
  ),
  venue_metrics as (
    select
      count(*)::integer as total_venues,
      count(*) filter (where venue_status = 'approved')::integer as approved,
      count(*) filter (where verification_status = 'verified')::integer as verified,
      count(*) filter (
        where venue_status = 'approved'
          and verification_status = 'verified'
          and public_listing_enabled = true
      )::integer as public_venues
    from public.venues
  ),
  partner_metrics as (
    select count(distinct venue_id)::integer as active_partners
    from public.venue_partner_profiles
    where is_active = true
  )
  select jsonb_build_object(
    'total_venues', v.total_venues,
    'approved_venues', v.approved,
    'verified_venues', v.verified,
    'public_venues', v.public_venues,
    'active_partners', p.active_partners,
    'total_assignments', a.total_assignments,
    'responded', a.responded,
    'bookings', a.bookings,
    'unresponded_24h', a.unresponded_24h,
    'response_rate', case
      when a.total_assignments = 0 then 0
      else round((a.responded::numeric / a.total_assignments::numeric) * 100, 1)
    end,
    'conversion_rate', case
      when a.total_assignments = 0 then 0
      else round((a.bookings::numeric / a.total_assignments::numeric) * 100, 1)
    end,
    'avg_response_minutes', coalesce(a.avg_response_minutes, 0)
  )
  into result
  from assignment_metrics a
  cross join venue_metrics v
  cross join partner_metrics p;

  return result;
end;
$function$;

revoke all on function public.smv_partner_analytics() from public;
revoke all on function public.smv_admin_analytics() from public;
grant execute on function public.smv_partner_analytics() to authenticated;
grant execute on function public.smv_admin_analytics() to authenticated;

-- Public directory remains safe-column-only and now has an explicit website
-- visibility switch independent of approval, verification and CRM assignment.
create or replace function public.smv_public_venues()
returns table (venue jsonb)
language sql
stable
security definer
set search_path = ''
as $function$
  select jsonb_build_object(
    'id', v.id,
    'venue_name', v.venue_name,
    'venue_type', v.venue_type,
    'description', v.description,
    'city', v.city,
    'area', v.area,
    'capacity_min', v.capacity_min,
    'capacity_max', v.capacity_max,
    'price_min_per_person', v.price_min_per_person,
    'price_max_per_person', v.price_max_per_person,
    'food_veg', v.food_veg,
    'food_non_veg', v.food_non_veg,
    'parking_available', v.parking_available,
    'rooms_available', v.rooms_available,
    'google_maps_url', v.google_maps_url,
    'featured', v.featured
  ) as venue
  from public.venues v
  where v.venue_status = 'approved'
    and v.verification_status = 'verified'
    and v.public_listing_enabled = true
  order by v.featured desc, v.venue_name asc;
$function$;

revoke all on function public.smv_public_venues() from public;
grant execute on function public.smv_public_venues() to anon, authenticated;

