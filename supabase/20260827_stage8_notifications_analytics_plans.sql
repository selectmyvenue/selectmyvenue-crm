create or replace function public.smv_mark_notification_read(
  p_notification_id bigint
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $function$
declare
  changed_count integer;
begin
  update public.venue_notifications n
  set
    is_read = true,
    read_at = coalesce(n.read_at, now())
  where n.id = p_notification_id
    and n.user_id = (select auth.uid())
    and exists (
      select 1
      from public.venue_partner_profiles p
      where p.user_id = (select auth.uid())
        and p.venue_id = n.venue_id
        and p.is_active = true
    );

  get diagnostics changed_count = row_count;
  return changed_count = 1;
end;
$function$;

create or replace function public.smv_mark_all_notifications_read()
returns integer
language plpgsql
security definer
set search_path = ''
as $function$
declare
  changed_count integer;
begin
  update public.venue_notifications n
  set
    is_read = true,
    read_at = coalesce(n.read_at, now())
  where n.user_id = (select auth.uid())
    and n.is_read = false
    and exists (
      select 1
      from public.venue_partner_profiles p
      where p.user_id = (select auth.uid())
        and p.venue_id = n.venue_id
        and p.is_active = true
    );

  get diagnostics changed_count = row_count;
  return changed_count;
end;
$function$;

revoke all on function public.smv_mark_notification_read(bigint) from public;
revoke all on function public.smv_mark_all_notifications_read() from public;
grant execute on function public.smv_mark_notification_read(bigint) to authenticated;
grant execute on function public.smv_mark_all_notifications_read() to authenticated;

create or replace function public.smv_create_assignment_notification()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
begin
  insert into public.venue_notifications (
    venue_id,
    user_id,
    assignment_id,
    notification_type,
    title,
    message,
    is_read
  )
  select
    new.venue_id,
    p.user_id,
    new.id,
    'new_assignment',
    'New enquiry assigned',
    'A new customer enquiry is ready in your Partner CRM.',
    false
  from public.venue_partner_profiles p
  where p.venue_id = new.venue_id
    and p.user_id is not null
    and p.is_active = true
    and not exists (
      select 1
      from public.venue_notifications n
      where n.assignment_id = new.id
        and n.user_id = p.user_id
        and n.notification_type = 'new_assignment'
    );

  return new;
end;
$function$;

