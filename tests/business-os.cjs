const {JSDOM}=require('jsdom');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(root,'dashboard.html'),'utf8');
const script=fs.readFileSync(path.join(root,'smv-business-os.js'),'utf8');
const css=fs.readFileSync(path.join(root,'smv-business-os.css'),'utf8');
assert(html.includes('smv-business-os.css')&&html.includes('smv-business-os.js'),'dashboard must load Business OS assets');
assert(css.includes('@media(max-width:560px)'),'Business OS must include narrow mobile layout');
const dom=new JSDOM(html,{url:'https://crm.selectmyvenue.com/dashboard.html',runScripts:'outside-only',pretendToBeVisual:true});
const w=dom.window,d=w.document;
d.getElementById('leadResultCount').textContent='125 enquiries';
d.getElementById('venueTotalCount').textContent='38';
for(const [key,count] of [['new',7],['today',12],['overdue',4],['unscheduled',9],['unassigned',3]]){
 const b=d.querySelector('[data-work-view="'+key+'"]');
 if(b)b.innerHTML=b.textContent+' <span>'+count+'</span>';
}
w.crm={loadEnquiries(){w.__refresh=(w.__refresh||0)+1;}};
let newClicked=0,venueClicked=0,overdueClicked=0;
d.getElementById('addEnquiryBtn').addEventListener('click',()=>newClicked++);
d.getElementById('venueManagementBtn').addEventListener('click',()=>venueClicked++);
d.querySelector('[data-work-view="overdue"]').addEventListener('click',()=>overdueClicked++);
w.eval(script);
const os=d.getElementById('smvBusinessOS');
assert(os,'Business OS panel should mount');
assert.equal(d.getElementById('smvOsLeads').textContent,'125');
assert.equal(d.getElementById('smvOsNew').textContent,'7');
assert.equal(d.getElementById('smvOsVenues').textContent,'38');
assert.equal(d.getElementById('smvOsOverdue').textContent,'4');
assert.equal(d.getElementById('smvOsToday').textContent,'12');
assert.equal(d.getElementById('smvOsUnscheduled').textContent,'9');
assert.equal(d.getElementById('smvOsUnassigned').textContent,'3');
d.querySelector('[data-os-action="new"]').click();
d.querySelector('[data-os-action="venues"]').click();
d.querySelector('[data-os-action="overdue"]').click();
d.querySelector('[data-os-action="refresh"]').click();
assert.equal(newClicked,1);assert.equal(venueClicked,1);assert.equal(overdueClicked,1);
assert.equal(w.__refresh,1);
console.log('PASS Business OS mounts, reflects live workspace counts and delegates quick actions to existing CRM controls');
