'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(root,'dashboard.html'),'utf8');
const js=fs.readFileSync(path.join(root,'smv-live-call-inventory.js'),'utf8');
const css=fs.readFileSync(path.join(root,'smv-live-call-inventory.css'),'utf8');
assert(html.includes('id="smvLiveInventoryResults"'),'assignment modal must show the live inventory results surface');
assert(html.includes('id="smvCallLocationSearch"'),'assignment modal must have a customer-location search');
assert(html.includes('smv-live-call-inventory.js'),'inventory controller must be loaded');
assert(html.includes('smv-live-call-inventory.css'),'premium inventory stylesheet must be loaded');
assert(!html.includes('id="smvAcEligible"')&&!html.includes('smv-assignment-kpis'),'old KPI dashboard must be removed from the user-facing assignment UI');
assert(js.includes('assignmentVenueRows'),'finder must reuse the existing approved venue inventory');
assert(js.includes('smv_assignment_venues') || js.includes('assignmentVenueRows'),'finder must consume CRM server-filtered approved and verified assignment inventory');
assert(js.includes('geo_area_aliases'),'area coordinates should be used when available');
assert(js.includes('minDistance-b.minDistance'),'nearby areas must be sorted by distance when coordinates exist');
assert(js.includes('data-slv-select'),'area inventory must allow selecting a venue');
assert(js.includes('.venue-assignment-checkbox'),'selection must connect to the existing assignment workflow');
assert(js.includes('preferred_area'),'current enquiry preferred area must prefill the finder');
assert(js.includes('customerPreferredArea'),'live lead-area typing must sync into the finder');
assert(!js.includes('.from("customer_enquiries")')&&!js.includes('.insert(')&&!js.includes('.update('),'finder must not write to customer enquiry or database tables');
assert(css.includes('.slv-area-card')&&css.includes('.slv-search-wrap')&&css.includes('@media(max-width:760px)'),'finder must have premium responsive styling');
console.log('PASS Live Call Inventory Finder: enquiry area sync, approved inventory, nearest-first area grouping, venue selection handoff and no database writes');

assert(!html.includes('smv-assignment-selection-dock'), 'do not render a second Selected Now panel below the assignment summary');
assert(!html.includes('smvInventorySelectedList'), 'single selection UI must remain the existing top-right assignment basket');
assert(js.includes('window.SMVEnterpriseAssignmentCenter?.updateBasket()'), 'live inventory selections must refresh the existing shared assignment basket');
assert(js.includes('cb.dispatchEvent(new Event("change",{bubbles:true}))'), 'inventory selections must enter the existing assignment checkbox/save flow');
