'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {spawnSync}=require('node:child_process');
const root=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(root,'dashboard.html'),'utf8');
const core=fs.readFileSync(path.join(root,'crm-core.js'),'utf8');
const employee=fs.readFileSync(path.join(root,'crm-employee-integration.js'),'utf8');
for(const file of ['crm-core.js','crm-employee-integration.js','smv-enterprise-assignment-center.js']){
 const check=spawnSync(process.execPath,['--check',path.join(root,file)],{encoding:'utf8'});
 assert.equal(check.status,0,file+' must parse without JavaScript syntax errors: '+check.stderr);
}
assert(html.includes('id="assignmentVenueSearch"'),'original assignment search field must remain available');
assert(html.includes('id="venueAssignmentList"'),'original assignment venue list must remain available');
assert(!html.includes('id="smvLiveCallInventory"')&&!html.includes('id="smvCallLocationSearch"'),'new Find Venues by Customer Location tool must be removed from the assignment modal');
assert(!html.includes('smv-live-call-inventory.js'),'new Live Call finder controller must not load');
assert(!html.includes('id="smvAiOpen"')&&!html.includes('id="smvAiDiscovery"'),'only the original Smart Venue Matches tool should be visible in the assignment workflow');
assert(!html.includes('ai-venue-discovery.js'),'secondary AI discovery controller must not load in the assignment modal');
assert(employee.includes('Smart Venue Matches'),'original Smart Venue Matches panel must still be rendered by the existing CRM matching controller');
assert(employee.includes('smvMatchTierControls'),'original Best Matches / Possible / All Venues / Assigned / Excluded filters must remain');
assert(employee.includes('function smartMatch(v,l)'),'original requirement-aware venue matcher must remain intact');
assert(employee.includes('smvEnsureRoadDistances'),'original matcher must calculate driving distances when coordinates are available');
assert(employee.includes("functions.invoke('route-distance'"),'road distances must use the existing OSRM route-distance Edge Function');
assert(employee.includes("distanceMode='road'"),'venue cards must distinguish road distance from straight-line fallback');
assert(employee.includes("match.distanceMode==='road'"),'venue cards must label driving distance and ETA when OSRM results are available');
assert(employee.includes('distanceLabel=match.distanceKm'),'venue cards must display the calculated distance beside each match');
const saveStart=core.indexOf('async function saveVenueAssignments');
const saveEnd=core.indexOf('function setupVenueAssignment',saveStart);
const saveBlock=core.slice(saveStart,saveEnd);
assert(saveBlock.includes('const selected = [...new Set(visibleSelected.map(String))]'),'only explicitly checked venues may be assigned');
assert(!saveBlock.includes('smvGetAssignmentSelection')&&!saveBlock.includes('smartSelected'),'recommended venues must never be silently assigned');
assert(saveBlock.includes('if (!selected.length)'),'assignment save must stop when no venue is selected');
console.log('PASS original Smart Venue Matches restored; new finder removed; explicit assignment save and OSRM distance checks present');
