'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(root,'dashboard.html'),'utf8');
const ai=fs.readFileSync(path.join(root,'ai-venue-discovery.js'),'utf8');
const center=fs.readFileSync(path.join(root,'smv-enterprise-assignment-center.js'),'utf8');
const css=fs.readFileSync(path.join(root,'ai-venue-discovery.css'),'utf8');
assert(html.includes('id="smvAssignmentControlCenter"'),'assignment modal must contain the enterprise control center');
for(const id of ['smvAcEligible','smvAcStrong','smvAcAvailable','smvAcSelected','smvAcBasketItems'])assert(html.includes('id="'+id+'"'),'control center missing '+id);
assert.match(html,/crm\.js[\s\S]*ai-venue-discovery\.js[\s\S]*smv-enterprise-assignment-center\.js/,'assignment controller must load after CRM and AI matching scripts');
assert(ai.includes('window.smvPrepareAssignmentCenter=async function(lead)'),'AI scorer must expose a lead-aware ranking adapter');
assert(ai.includes('score(v,c,loc,radius)'),'ranking must reuse the explainable AI score');
assert(ai.includes('eligibility(v,m,c,strict)'),'ranking must retain the match eligibility gate');
assert(center.includes('window.smvPrepareAssignmentCenter(current)'),'control center must use the AI ranking adapter');
assert(center.includes('data confidence'),'match cards must display data confidence');
assert(center.includes('Partner available'),'partner availability state must be visible');
assert(center.includes('window.confirm(message)'),'assignment save must require explicit final staff confirmation');
assert(center.includes('Existing active assignments will be preserved'),'confirmation must disclose append-only semantics');
assert(!center.includes('.from("customer_enquiries")'),'control center must not write customer enquiries');
assert(!center.includes('.insert(')&&!center.includes('.update('),'control center must not perform database writes');
assert(css.includes('.smv-assignment-kpis')&&css.includes('.smv-assignment-basket'),'enterprise control center must have responsive KPI and basket styling');
console.log('PASS Enterprise Assignment Center: unified AI ranking, evidence/confidence, partner state, selection basket, final approval and no direct database writes');
